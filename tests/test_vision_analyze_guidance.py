"""vision_analyze 工具描述必须带判据，否则别的会话会把模型自述当错误码。

2026-11-21：另一个会话拿 `[Unsupported Image]` 当检测结论，推断"兜底链配了不支持
图片的模型"，然后去改了视觉配置。实际那句话是模型自己生成的文字，仓库里根本没有
这个字符串。工具描述是模型每次调用前必读的位置，比技能索引可靠，判据写死在这里。
"""

import pytest

from tools.registry import registry
import tools.vision_tools  # noqa: F401  触发注册

SCHEMA = registry.get_schema("vision_analyze")
DESC = (SCHEMA or {}).get("description") or ""


def test_description_present():
    assert DESC, "vision_analyze 工具描述为空"


def test_flags_model_claim_not_error_code():
    """必须点明 [Unsupported Image] 是模型生成的句子，不是工具抛的错。"""
    assert "[Unsupported Image]" in DESC
    low = DESC.lower()
    assert "generated by a model" in low
    assert "not raised by this tool" in low


def test_requires_multicolour_probe():
    """单色图可以靠猜蒙对，所以判据必须是多色图。"""
    low = DESC.lower()
    assert "multi-colour" in low or "multicolour" in low
    assert "guess" in low


def test_names_reasoning_budget_trap():
    """正文为空 + reasoning 撞满 = 被思考吃光，不是看不见。"""
    low = DESC.lower()
    assert "reasoning_tokens" in low or "reasoning tokens" in low
    assert "reasoning_effort" in DESC


def test_states_that_fallback_chain_reads_images():
    """本机 provider=auto，真正读图的是 fallback_chain[0]，不是主模型。"""
    assert "fallback_chain" in DESC
    assert "not the main model" in DESC.lower()


def test_points_at_runbook():
    assert "references/vision-model-howto.md" in DESC


def test_schema_still_valid_tool_schema():
    """改描述不能碰坏 schema 本身。"""
    params = SCHEMA["parameters"]
    assert params["type"] == "object"
    assert set(params["required"]) == {"image_url", "question"}
    assert "image_url" in params["properties"]
